assert.equal(A.selectAlerts('Popdex',[p],reset.next,now+3000).alerts.length,0);
assert.equal(A.selectAlerts('Popdex',[{...p,rows:[{t:now+3600000}]}],reset.next,now+3900000).alerts.length,1);
