const assert=require('node:assert/strict'),D=require('./data.cjs'),S=require('./scan-engine.js');
const now=1800000000000,bar=300000;
const market={id:'A',symbol:'NVDA-USD',type:'PERPETUAL',tradfi:true,price:100,status:'ONLINE',takerBps:2,volume:1e7};
const q=D.arcusQuote(market,{bestBid:{price:'99.99',size:'5'},bestAsk:{price:'100.01',size:'5'},timestamp:now*1000});
assert.equal(q.quoteTime,now);assert.ok(Math.abs(q.spread-2)<1e-8);
assert.equal(D.arcusQuote(market,{bestBid:{price:101,size:1},bestAsk:{price:100,size:1}}).spread,null);
assert.equal(D.arcusQuote(market,{}).quoteTime,null);
const v=D.variationalMarkets({listings:[{ticker:'NVDA-PERP',name:'NVIDIA Corporation',contract_type:'perpetual',mark_price:'100',quotes:{updated_at:new Date(now).toISOString(),size_1k:{bid:'99',ask:'101'}}}]})[0];
assert.equal(v.takerBps,0);assert.equal(v.spread,200);assert.equal(v.requireQuote,true);
let store={markets:{}};
for(let i=0;i<240;i++)store=D.record(store,[v],now-(240-i)*bar+270000);
assert.equal(D.sampledHistory(store,v.id,now+2000).length,240);
store=D.record(store,[{...v,price:102}],now+20000);
store=D.record(store,[{...v,price:103}],now+270000);
assert.equal(store.markets[v.id].length,241);
assert.equal(D.sampledHistory(store,v.id,now+290000).length,240);
assert.equal(D.sampledHistory(store,v.id,now+bar+2000).at(-1).c,103);
const short=D.record({markets:{}},[v],now+10000);
assert.equal(D.sampledHistory(short,v.id,now+bar+2000).length,0); // early-only observation discarded
const restart=JSON.parse(JSON.stringify(store));assert.deepEqual(D.sampledHistory(restart,v.id,now+bar+2000),D.sampledHistory(store,v.id,now+bar+2000));
const rows=Array.from({length:240},(_,i)=>({t:now-(240-i)*bar,a:Math.exp(4+i*.001+.01*Math.sin(i*.4)),b:Math.exp(4+i*.001)}));
const engine={stats:()=>({beta:1,alpha:0,sd:.01,z:2,confirm:2}),fit:()=>({alpha:0,beta:1}),corr:()=>.8};
const pair={a:q,b:{...q,id:'B'},group:'semiconductors'};
assert.equal(S.analyze(pair,rows,engine,now).setup,true);
for(const bad of [{quoteTime:now-121000},{quoteTime:now+6000},{quoteTime:null},{bid:null},{spread:null}])assert.equal(S.analyze({...pair,a:{...q,...bad}},rows,engine,now).eligible,false);
assert.equal(S.analyze(pair,rows.slice(0,239),engine,now).eligible,false);
const gaps=rows.filter((_,i)=>![30,60,90].includes(i));
assert.equal(S.analyze(pair,gaps,engine,now).eligible,false);
console.log('Quote validation, setup gating, observation warm-up, persistence and missing-bucket checks passed');
